/** 학생이 쓴 글을 태그로 감싸 지시문과 섞이지 않게 한다. */
export function wrapUserInput(text: string): string {
  const safe = text.replaceAll('<', '‹').replaceAll('>', '›');
  return `<사용자입력>${safe}</사용자입력>`;
}
